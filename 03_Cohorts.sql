)
WHERE RANK = 1
)
,

EGFR_READ AS
(
SELECT
ALF_PE,
EVENT_DT_EGFR AS TEST,
EVENT_VAL
FROM
(
SELECT
	M.ALF_PE,
	EVENT_CD,
	EVENT_DT AS EVENT_DT_EGFR,
	EVENT_VAL,
	CASE
		WHEN R.PREF_TERM_198 IS NULL AND R.PREF_TERM_60 IS NULL THEN R.PREF_TERM_30
		WHEN R.PREF_TERM_198 IS NULL THEN R.PREF_TERM_60
		ELSE PREF_TERM_198
	END AS DESC		
FROM ALFS M

JOIN SAILW1483V.EXTRACT_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

LEFT JOIN SAILUKHDV.READ_CD_CV2_SCD R
ON GP.EVENT_CD = R.READ_CODE
	
WHERE 
	GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
	AND (R.PREF_TERM_30 LIKE('%eGFR%')
		OR R.PREF_TERM_30 LIKE('%Glom%'))
	AND EVENT_VAL IS NOT NULL
	AND EVENT_VAL > 0
)
),

EGFR_WRRS AS
(
SELECT
ALF_PE,
TEST,
VAL AS EVENT_VAL
FROM
(
SELECT
	W.ALF_PE,
	SPCM_COLLECTED_DT AS TEST,
	VAL_TYPE,
	CODE,	
	NAME,	
	READ_CD,
	CAST(
	CASE 
		WHEN VAL = '>90' THEN 91
		WHEN VAL = '>60' THEN 61
		ELSE VAL END
	AS INTEGER) AS VAL,	
	UNITOFMEASUREMENT
FROM 
	SAILW1483V.EXTRACT_WRRS_OBSERVATION_RESULT W

JOIN ALFS F
ON W.ALF_PE = F.ALF_PE
	
WHERE NAME LIKE('%GFR%')
	AND SPCM_COLLECTED_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
	AND VAL IS NOT NULL
	AND VAL_TYPE = 'SN'
	AND VAL NOT IN('{redacted}','Serum Haemolysed','Not available.','NA (No sample)','NA','Insufficient sample','<0.1','NA (TEST NOT PERFORMED.)','NA (Insufficient)','>165','<20','Not Tested','<18','<15','Not Available','>3270.8','<13','NA (Haemolysed specimen)')
)
),

EGFR AS
(
SELECT
ALF_PE,
EGFR,
EGFR_VAL
FROM
(
SELECT
ALF_PE,
CASE 
	WHEN EVENT_VAL > 60 THEN '> 60'
	WHEN EVENT_VAL BETWEEN 30 AND 60 THEN '30 - 60'		
	WHEN EVENT_VAL < 30 THEN '< 30'		
END AS EGFR,
EVENT_VAL AS EGFR_VAL,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY TEST DESC) AS RANK
FROM
(
SELECT
*
FROM EGFR_WRRS

UNION

SELECT
*
FROM EGFR_READ
)
)
WHERE RANK = 1
)
,

LDL_READ AS
(
SELECT
ALF_PE,
FIRST_DATE,
EVENT_DT_LIPID AS TEST,
EVENT_VAL
FROM
(
SELECT 
	M.ALF_PE,
	FIRST_DATE,
	GP.EVENT_DT AS EVENT_DT_LIPID,
	GP.EVENT_VAL,
	D.READ_TYPE,
	D.READ_CODE	
FROM ALFS M

JOIN SAILW1483V.EXTRACT_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_LIPID_READ D
ON GP.EVENT_CD = D.READ_CODE

WHERE GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
AND READ_TYPE = 'LDL'

ORDER BY M.ALF_PE, GP.EVENT_DT
)
),

LDL_WRRS AS
(
SELECT
ALF_PE,
FIRST_DATE,
TEST,
VAL AS EVENT_VAL
FROM
(
SELECT
	W.ALF_PE,
	FIRST_DATE,
	SPCM_COLLECTED_DT AS TEST,
	VAL_TYPE,
	CODE,	
	NAME,	
	READ_CD,
	CAST(VAL AS DECIMAL(31,8)) AS VAL,	
	UNITOFMEASUREMENT
FROM 
	SAILW1483V.EXTRACT_WRRS_OBSERVATION_RESULT W

JOIN ALFS F
ON W.ALF_PE = F.ALF_PE
	
WHERE CODE LIKE('LDL%')
	AND SPCM_COLLECTED_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
	AND VAL IS NOT NULL
	AND VAL_TYPE = 'SN'
	AND VAL NOT IN('{redacted}','Serum Haemolysed','Not available.','NA (No sample)','NA','Insufficient sample','<0.1','NA (TEST NOT PERFORMED.)','NA (Insufficient)')
)
)
,

LDL AS
(
SELECT
ALF_PE, 
TEST,
LDL, 
LDL_VAL
FROM
(
SELECT
ALF_PE,
FIRST_DATE,
CASE 
	WHEN EVENT_VAL > 3.5 THEN '> 3.5'		
	WHEN EVENT_VAL BETWEEN 2.5 AND 3.5 THEN '2.5 - 3.5'	
	WHEN EVENT_VAL < 2.5 THEN '< 2.5'		
END AS LDL,
EVENT_VAL AS LDL_VAL,
TEST,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY TEST DESC) AS RANK
FROM
(
SELECT
*
FROM LDL_WRRS

UNION

SELECT
*
FROM LDL_READ
)
)
WHERE RANK = 1
)
,

ALF_LDL_COMB AS
(
SELECT
ALF_PE,
CASE WHEN L.ALF_PE IS NOT NULL THEN TEST ELSE A.FIRST_DATE END AS DT
FROM ALFS A

LEFT JOIN LDL L
USING (ALF_PE)
)
--SELECT COUNT(DISTINCT ALF_PE) FROM ALF_LDL_COMB
,

SBP AS
(
SELECT
ALF_PE,
SBP
FROM
(
SELECT
B.ALF_PE,
EVENT_DT,
CASE WHEN SYS = 999 OR SYS = -999 THEN NULL ELSE SYS END AS SBP,
ROW_NUMBER() OVER(PARTITION BY B.ALF_PE ORDER BY EVENT_DT DESC) AS RANK
FROM ALFS A

JOIN SAILW1483V.ASCVD_BLOOD_PRESSURES B
ON A.ALF_PE = B.ALF_PE

WHERE B.EVENT_DT BETWEEN A.FIRST_DATE - 1 YEARS AND A.FIRST_DATE + 30 DAYS
)
WHERE RANK = 1
)
,

LLT AS
(
SELECT
ALF_PE,
CASE 
	WHEN INEGY = 1 THEN 4
	WHEN (HI_STAT = 1 OR LI_STAT = 1) AND EZET_FIBR = 1 THEN 4
	WHEN HI_STAT = 1 AND LI_STAT = 1 THEN 3
	WHEN HI_STAT = 1 THEN 3		
	WHEN LI_STAT = 1 THEN 2	
	WHEN EZET_FIBR = 1 THEN 1
	ELSE 0
END AS LLT_INT,
CASE 
	WHEN INEGY = 1 OR HI_STAT = 1 OR LI_STAT = 1 THEN 1
	ELSE 0
END AS STATIN
FROM
(
SELECT
ALF_PE,
MAX(HI_STAT) AS HI_STAT,
MAX(LI_STAT) AS LI_STAT,
MAX(INEGY) AS INEGY,
MAX(EZET_FIBR) AS EZET_FIBR
FROM 
(
SELECT
A.ALF_PE,
CASE WHEN READ_TYPE = 'HIGH_STATIN' 						THEN '1' ELSE '0' END AS HI_STAT,
CASE WHEN READ_TYPE = 'LOW_STATIN' 							THEN '1' ELSE '0' END AS LI_STAT,
CASE WHEN READ_TYPE = 'INEGY' 								THEN '1' ELSE '0' END AS INEGY,
CASE WHEN READ_TYPE = 'EZETIMIBE' OR READ_TYPE = 'FIBRATE'	THEN '1' ELSE '0' END AS EZET_FIBR
FROM ALF_LDL_COMB A

JOIN SAILW1483V.EXTRACT_WLGP_GP_EVENT_CLEANSED GP
ON A.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_DRUG_READ D
ON GP.EVENT_CD = D.READ_CODE

WHERE EVENT_DT BETWEEN DT - 60 DAYS AND DT
AND READ_TYPE IN('HIGH_STATIN', 'LOW_STATIN', 'INEGY', 'EZETIMIBE', 'FIBRATE')
)
GROUP BY ALF_PE
)
)
,

ANTI_HTN_1 AS 
(
SELECT
GP.ALF_PE,
CASE WHEN L.ANTIHYPERTENSIVE_CLASS LIKE 'CENTRAL' THEN 'X'
WHEN L.ANTIHYPERTENSIVE_CLASS LIKE 'ALFA' THEN 'L'
ELSE L.ANTIHYPERTENSIVE_CLASS END AS DRUG_CLASS
FROM ALFS A

JOIN SAILW1483V.EXTRACT_WLGP_GP_EVENT_CLEANSED GP
ON A.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.HYPERTENSIVE_DRUGS L
ON GP.EVENT_CD = L.READ_CODE

WHERE EVENT_DT BETWEEN FIRST_DATE - 60 DAYS AND FIRST_DATE
)
,

ANTI_HTN_2 AS 
(
SELECT 
ALF_PE,
MAX(CASE WHEN DRUG_CLASS LIKE '%A%' THEN 1 ELSE 0 END) AS DRUG_A,
MAX(CASE WHEN DRUG_CLASS LIKE '%B%' THEN 1 ELSE 0 END) AS DRUG_B,
MAX(CASE WHEN DRUG_CLASS LIKE '%C%' THEN 1 ELSE 0 END) AS DRUG_C,
MAX(CASE WHEN DRUG_CLASS LIKE '%D%' THEN 1 ELSE 0 END) AS DRUG_D,
MAX(CASE WHEN DRUG_CLASS LIKE '%K%' THEN 1 ELSE 0 END) AS DRUG_K,
MAX(CASE WHEN DRUG_CLASS LIKE '%L%' THEN 1 ELSE 0 END) AS DRUG_ALFA,
MAX(CASE WHEN DRUG_CLASS LIKE '%V%' THEN 1 ELSE 0 END) AS DRUG_V,
MAX(CASE WHEN DRUG_CLASS LIKE '%X%' THEN 1 ELSE 0 END) AS DRUG_Central
FROM ANTI_HTN_1

GROUP BY ALF_PE
)
,

ANTI_HTN AS
(
SELECT
ALF_PE,
CASE WHEN CLASSES >= 4 THEN 4 ELSE CLASSES END AS AHT_INT,
CASE WHEN CLASSES >= 1 THEN 1 ELSE 0 END AS AHT
FROM
(
SELECT 
A.ALF_PE,
CASE WHEN P.ALF_PE IS NOT NULL THEN (DRUG_A + DRUG_B + DRUG_C + DRUG_D + DRUG_K + DRUG_ALFA + DRUG_V + DRUG_Central) 
ELSE 0 END AS CLASSES 
FROM ALFS A

LEFT JOIN ANTI_HTN_2 P
USING(ALF_PE)
)
)

SELECT 
	M.ALF_PE, 
	M.FIRST_DATE AS DIAG_DT,
	M.CENSOR_DATE AS CNS_DT,
	'ASCVD' AS COHORT,
	G.LSOA2011_CD AS LSOA,
	G.MSOA_CD AS MSOA,
	G.LAD_CD AS LAD,
	CASE WHEN H.ALF_PE IS NOT NULL THEN 1 ELSE 0 END AS HE,
	CASE 
	WHEN M.GENDER = 1 THEN 'M'
	WHEN M.GENDER = 2 THEN 'F'
	ELSE NULL END AS SEX, 
	G.WIMD_2019_QUINTILE AS WIMD, 
	td.tds AS TOWNSEND,
    COALESCE(M.ETHNICITY, 'Unknown')    AS ETHN,
	M.AGE_DIAG AS AGE, 
	CASE WHEN M.TYPE = 'ST' THEN 'Stroke' ELSE M.TYPE END AS TYPE, 
	SMK,
	M.BMI,
	CASE WHEN DM IS NULL THEN 0 ELSE DM END AS DM, 
	CASE WHEN DMTA IS NULL THEN 0 ELSE DMTA END AS DMTA, 
	CASE WHEN LVR IS NULL THEN 0 ELSE LVR END AS LVR, 
	CASE WHEN HTN IS NULL THEN 0 ELSE HTN END AS HTN, 
	CASE WHEN HF IS NULL THEN 0 ELSE HF END AS HF,
	CASE WHEN AF IS NULL THEN 0 ELSE AF END AS AF,	
	CASE WHEN RA IS NULL THEN 0 ELSE RA END AS RA,
	CASE WHEN FH_CVD IS NULL THEN 0 ELSE FH_CVD END AS FH_CVD,	
	CASE WHEN X.CKD IS NULL THEN 0 ELSE X.CKD END AS CKD,		
	CASE WHEN LLT_INT IS NULL THEN 0 ELSE LLT_INT END AS LLT_INT,
	CASE WHEN STATIN IS NULL THEN 0 ELSE STATIN END AS STATIN,	
	CASE WHEN AHT_INT IS NULL THEN 0 ELSE AHT_INT END AS AHT_INT,	
	CASE WHEN AHT IS NULL THEN 0 ELSE AHT END AS AHT,
	LDL,
	LDL_VAL,	
	NHDL,
	NHDL_VAL,
	TC_HDL,
	EGFR,
	EGFR_VAL,
	SBP AS SBP_VAL
FROM SAILW1483V.COHORT_MASTER_FINAL M

JOIN ALFS A
USING(ALF_PE)

LEFT JOIN MORB_MAX X
USING(ALF_PE)

LEFT JOIN 
(
SELECT DISTINCT ALF_PE FROM SAILW1483V.P3_ASCVD_HARD_EVENTS_CLASS
WHERE EVENT_DT BETWEEN FIRST_DATE AND FIRST_DATE + 7
AND CLASS = 'MACE'
) H
USING(ALF_PE)

LEFT JOIN 
(
SELECT
L.*,
MSOA11CD AS MSOA_CD,
LAD11CD AS LAD_CD
FROM
(
SELECT 
W.*,
ROW_NUMBER() OVER(PARTITION BY W.ALF_PE ORDER BY START_DATE DESC) AS RANK
FROM SAILW1483V.EXTRACT_WDSD_SINGLE_CLEAN_GEO_CHAR_LSOA2011  W

JOIN SAILW1483V.COHORT_MASTER_FINAL M
USING(ALF_PE)

WHERE 
LSOA2011_CD <> 'N/A' 
AND ((M.FIRST_DATE BETWEEN START_DATE AND END_DATE) 
	OR (M.FIRST_DATE < START_DATE AND END_DATE = '9999-01-01'))
) L

JOIN (SELECT LSOA11CD, MSOA11CD, LAD11CD FROM SAILW1483V.LSOA_MSOA_LAD_ENGLAND_WALES WHERE LSOA11CD LIKE ('W%') GROUP BY LSOA11CD, MSOA11CD, LAD11CD) W
ON LSOA2011_CD = LSOA11CD

WHERE RANK = 1
) G
USING(ALF_PE)

LEFT JOIN EGFR E
USING (ALF_PE)

LEFT JOIN NHDL N
USING (ALF_PE)

LEFT JOIN LDL L
USING (ALF_PE)

LEFT JOIN SBP S
USING (ALF_PE)

LEFT JOIN TC_HDL
USING (ALF_PE)

LEFT JOIN LLT
USING (ALF_PE)

LEFT JOIN ANTI_HTN
USING (ALF_PE)

LEFT JOIN SAILW1483V.TOWNS_DEP_SCORE td 
ON td.GEO_CODE = G.LSOA2011_CD

WHERE M.AGE_DIAG BETWEEN 25 AND 84
; 
COMMIT;
