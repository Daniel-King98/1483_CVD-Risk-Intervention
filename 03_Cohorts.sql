)
,

MORBS AS
(
SELECT
A.ALF_PE,
GP.EVENT_DT,
M.READ_TYPE
FROM ALFS A

JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
ON A.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_MORB_READ M
ON GP.EVENT_CD = M.READ_CODE

WHERE GP.EVENT_DT < FIRST_DATE
)
,

MORB_SELECT AS
(
SELECT
ALF_PE,
EVENT_DT,
READ_TYPE
FROM 
(
SELECT
*,
ROW_NUMBER() OVER(PARTITION BY ALF_PE, READ_TYPE ORDER BY EVENT_DT) AS RANK
FROM MORBS

WHERE READ_TYPE IN('DIABETES','DEMENTIA','LIVER_DISEASE','HEART_FAILURE','HYPERTENSION','AF')
)
WHERE RANK = 1
)
,

MORB_MAX AS
(
SELECT
ALF_PE,
MAX (DIABETES) 				AS DM,
MAX (DEMENTIA) 				AS DMTA,
MAX (LIVER) 				AS LVR,
MAX (HF) 					AS HF,
MAX (HYPERTENSION) 			AS HTN,
MAX (AF) 					AS AF,
MAX (RA) 					AS RA,
MAX (FH_CVD) 				AS FH_CVD,
MAX (CKD) 					AS CKD,
MAX (SMOKING_STATUS) 		AS SMK
FROM 
(
SELECT 
A.ALF_PE,
CASE WHEN READ_TYPE = 'DIABETES' 			THEN 1 ELSE 0 END AS DIABETES,
CASE WHEN READ_TYPE = 'DEMENTIA'			THEN 1 ELSE 0 END AS DEMENTIA,
CASE WHEN READ_TYPE = 'LIVER_DISEASE' 		THEN 1 ELSE 0 END AS LIVER,
CASE WHEN READ_TYPE = 'HEART_FAILURE' 		THEN 1 ELSE 0 END AS HF,
CASE WHEN READ_TYPE = 'HYPERTENSION' 		THEN 1 ELSE 0 END AS HYPERTENSION,
CASE WHEN READ_TYPE = 'AF' 					THEN 1 ELSE 0 END AS AF,
CASE WHEN ra.ALF_PE IS NOT NULL 			THEN 1 ELSE 0 END AS RA,
CASE WHEN fh.ALF_PE IS NOT NULL 			THEN 1 ELSE 0 END AS FH_CVD,
CASE WHEN ckd.ALF_PE IS NOT NULL 			THEN 1 ELSE 0 END AS CKD,
smk.SMOKER AS SMOKING_STATUS
FROM MORB_SELECT A

LEFT JOIN RA       ra  ON ra.ALF_PE  = A.ALF_PE
LEFT JOIN FH_CVD   fh  ON fh.ALF_PE  = A.ALF_PE
LEFT JOIN SMOKING  smk ON smk.ALF_PE = A.ALF_PE
LEFT JOIN CKD  	   ckd ON ckd.ALF_PE = A.ALF_PE
)
GROUP BY ALF_PE
)
,

NHDL_READ AS
(
SELECT
ALF_PE,
EVENT_DT_LIPID AS TEST,
EVENT_VAL
FROM
(
SELECT 
	T.ALF_PE,
	T.EVENT_DT AS EVENT_DT_LIPID,
	T.EVENT_VAL - H.EVENT_VAL AS EVENT_VAL
FROM
(
SELECT 
	M.ALF_PE,
	GP.EVENT_DT,
	GP.EVENT_VAL
FROM ALFS M

JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_LIPID_READ D
ON GP.EVENT_CD = D.READ_CODE

WHERE GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
AND READ_TYPE = 'TC'
) T

JOIN
(
SELECT 
	M.ALF_PE,
	GP.EVENT_DT,
	GP.EVENT_VAL
FROM ALFS M

JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_LIPID_READ D
ON GP.EVENT_CD = D.READ_CODE

WHERE GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
AND READ_TYPE = 'HDL'
) H
ON T.ALF_PE = H.ALF_PE
AND T.EVENT_DT = H.EVENT_DT

UNION

SELECT 
	M.ALF_PE,
	GP.EVENT_DT AS EVENT_DT_LIPID,
	GP.EVENT_VAL
FROM ALFS M

JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_LIPID_READ D
ON GP.EVENT_CD = D.READ_CODE

WHERE GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
AND READ_TYPE = 'NON_HDL'
)
),

NHDL_WRRS AS
(
SELECT
ALF_PE,
TEST,
VAL AS EVENT_VAL
FROM
(
SELECT
	W.ALF_PE,
	SPCM_COLLECTED_DT AS TEST,
	VAL_TYPE,
	CODE,	
	NAME,	
	READ_CD,
	CAST(VAL AS DECIMAL(31,8)) AS VAL,	
	UNITOFMEASUREMENT
FROM 
	SAILW1483V.EXTRACT_P2_WRRS_OBSERVATION_RESULT W

JOIN ALFS F
ON W.ALF_PE = F.ALF_PE
	
WHERE CODE LIKE('NHDL%')
	AND SPCM_COLLECTED_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
	AND VAL IS NOT NULL
	AND VAL > 0
	AND VAL_TYPE = 'SN'
	AND VAL NOT IN('{redacted}','Serum Haemolysed','Not available.','NA (No sample)','NA','Insufficient sample','<0.1','NA (TEST NOT PERFORMED.)','NA (Insufficient)')
)
)
,

NHDL AS
(
SELECT
ALF_PE,
NHDL,
NHDL_VAL
FROM
(
SELECT
ALF_PE,
CASE 
	WHEN EVENT_VAL > 4.3 THEN '> 4.3'		
	WHEN EVENT_VAL <= 4.3 THEN '<= 4.3'		
END AS NHDL,
EVENT_VAL AS NHDL_VAL,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY TEST DESC) AS RANK
FROM
(
SELECT
*
FROM NHDL_WRRS

UNION

SELECT
*
FROM NHDL_READ
)
)
WHERE RANK = 1
)
,

TC_HDL AS
(
SELECT
ALF_PE,
TC_HDL
FROM
(
	SELECT
	ALF_PE,
	EVENT_VAL AS TC_HDL,
	ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY EVENT_DT DESC) AS RANK
	FROM
	(
		SELECT 
			T.ALF_PE,
			T.EVENT_DT,
			CAST(T.EVENT_VAL AS DECIMAL(31,8)) / CAST(H.EVENT_VAL AS DECIMAL(31,8)) AS EVENT_VAL
		FROM
		(
			SELECT 
				M.ALF_PE,
				GP.EVENT_DT,
				GP.EVENT_VAL
			FROM ALFS M
			
			JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
			ON M.ALF_PE = GP.ALF_PE
			
			JOIN SAILW1483V.PHEN_LIPID_READ D
			ON GP.EVENT_CD = D.READ_CODE
			
			WHERE GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
			AND READ_TYPE = 'TC'
		) T
		
		JOIN
		(
			SELECT 
				M.ALF_PE,
				GP.EVENT_DT,
				GP.EVENT_VAL
			FROM ALFS M
			
			JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
			ON M.ALF_PE = GP.ALF_PE
			
			JOIN SAILW1483V.PHEN_LIPID_READ D
			ON GP.EVENT_CD = D.READ_CODE
			
			WHERE GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
			AND READ_TYPE = 'HDL'
		) H
		ON T.ALF_PE = H.ALF_PE
		AND T.EVENT_DT = H.EVENT_DT
	)
)
WHERE RANK = 1
)
,

EGFR_READ AS
(
SELECT
ALF_PE,
EVENT_DT_EGFR AS TEST,
EVENT_VAL
FROM
(
SELECT
	M.ALF_PE,
	EVENT_CD,
	EVENT_DT AS EVENT_DT_EGFR,
	EVENT_VAL,
	CASE
		WHEN R.PREF_TERM_198 IS NULL AND R.PREF_TERM_60 IS NULL THEN R.PREF_TERM_30
		WHEN R.PREF_TERM_198 IS NULL THEN R.PREF_TERM_60
		ELSE PREF_TERM_198
	END AS DESC		
FROM ALFS M

JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

LEFT JOIN SAILUKHDV.READ_CD_CV2_SCD R
ON GP.EVENT_CD = R.READ_CODE
	
WHERE 
	GP.EVENT_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
	AND (R.PREF_TERM_30 LIKE('%eGFR%')
		OR R.PREF_TERM_30 LIKE('%Glom%'))
	AND EVENT_VAL IS NOT NULL
	AND EVENT_VAL > 0
)
),

EGFR_WRRS AS
(
SELECT
ALF_PE,
TEST,
VAL AS EVENT_VAL
FROM
(
SELECT
	W.ALF_PE,
	SPCM_COLLECTED_DT AS TEST,
	VAL_TYPE,
	CODE,	
	NAME,	
	READ_CD,
	CAST(
	CASE 
		WHEN VAL = '>90' THEN 91
		WHEN VAL = '>60' THEN 61
		ELSE VAL END
	AS INTEGER) AS VAL,	
	UNITOFMEASUREMENT
FROM 
	SAILW1483V.EXTRACT_P2_WRRS_OBSERVATION_RESULT W

JOIN ALFS F
ON W.ALF_PE = F.ALF_PE
	
WHERE NAME LIKE('%GFR%')
	AND SPCM_COLLECTED_DT BETWEEN FIRST_DATE - 1 YEAR AND FIRST_DATE + 30 DAYS
	AND VAL IS NOT NULL
	AND VAL_TYPE = 'SN'
	AND VAL NOT IN('{redacted}','Serum Haemolysed','Not available.','NA (No sample)','NA','Insufficient sample','<0.1','NA (TEST NOT PERFORMED.)','NA (Insufficient)','>165','<20','Not Tested','<18','<15','Not Available','>3270.8','<13','NA (Haemolysed specimen)')
)
),

EGFR AS
(
SELECT
ALF_PE,
EGFR,
EGFR_VAL
FROM
(
SELECT
ALF_PE,
CASE 
	WHEN EVENT_VAL > 60 THEN '> 60'
	WHEN EVENT_VAL BETWEEN 30 AND 60 THEN '30 - 60'		
	WHEN EVENT_VAL < 30 THEN '< 30'		
END AS EGFR,
EVENT_VAL AS EGFR_VAL,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY TEST DESC) AS RANK
FROM
(
SELECT
*
FROM EGFR_WRRS

UNION

SELECT
*
FROM EGFR_READ
)
)
WHERE RANK = 1
)
,

LDL_READ AS
(
SELECT
ALF_PE,
FIRST_DATE,
EVENT_DT_LIPID AS TEST,
EVENT_VAL
FROM
(
SELECT 
	M.ALF_PE,
	FIRST_DATE,
	GP.EVENT_DT AS EVENT_DT_LIPID,
	GP.EVENT_VAL,
	D.READ_TYPE,
	D.READ_CODE	
FROM ALFS M

JOIN SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP
ON M.ALF_PE = GP.ALF_PE

JOIN SAILW1483V.PHEN_LIPID_READ D
ON GP.EVENT_CD = D.READ_CODE

