WITH ALFS AS
(
SELECT 
	ALF_PE,
	FIRST_DATE
FROM 
	SAILW1483V.P2_DIABETES_COHORT_MASTER M

WHERE YEAR(FIRST_DATE) IN(2022,2023)
)

--SELECT COUNT(DISTINCT ALF_PE) FROM ALFS
,

-- RHEUMATOID ARTHRITIS  
RA_WLGP AS (
    SELECT DISTINCT e.ALF_PE
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD IN (
        '66HB0',  -- RA monitoring
        'N040.',  -- Rheumatoid arthritis
        'N0402',  -- RA of shoulder
        'N0408',  -- RA of MCP joint
        'N0409',  -- RA of PIP joint of finger
        'N0405',  -- RA of elbow
        'N0400',  -- RA of cervical spine
        'N040D',  -- RA of knee
        'N040F',  -- RA of ankle
        'N04..',  -- RA and other inflammatory polyarthropathy
        'N0407',  -- RA of wrist
        'N040C',  -- RA of sacro-iliac joint
        'N0406',  -- RA of distal radio-ulnar joint
        'N040A',  -- RA of DIP joint of finger
        'N040B'   -- RA of hip
    )
    AND e.EVENT_DT < c.FIRST_DATE
),

RA_PEDW AS (
    SELECT DISTINCT S.ALF_PE
    FROM SAILW1483V.EXTRACT_P2_PEDW_SPELL S
    
JOIN SAILW1483V.EXTRACT_P2_PEDW_EPISODE E
	ON E.PROV_UNIT_CD = S.PROV_UNIT_CD 
	AND E.SPELL_NUM_PE = S.SPELL_NUM_PE

JOIN SAILW1483V.EXTRACT_P2_PEDW_DIAG D
	ON E.PROV_UNIT_CD = D.PROV_UNIT_CD
	AND E.SPELL_NUM_PE = D.SPELL_NUM_PE
	AND E.EPI_NUM = D.EPI_NUM	
 
INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON S.ALF_PE = c.ALF_PE
    
WHERE D.DIAG_CD_1234 IN ('M069', 'M068', 'M061', 'M060', 'M064')
AND s.ADMIS_DT < c.FIRST_DATE
),

RA AS (
    SELECT ALF_PE FROM RA_WLGP
    UNION
    SELECT ALF_PE FROM RA_PEDW
)

--SELECT * FROM RA
,

--FAMILY HISTORY OF ANGINA / MI
FH_CVD AS (
    SELECT DISTINCT e.ALF_PE
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD IN (
        '12CN.',  -- FH: MI 1st degree female relative <65
        '12CL.',  -- FH: Angina 1st degree female relative <65
        '12CP.',  -- FH: MI 1st degree male relative <55
        '12CM.'   -- FH: Angina 1st degree male relative <55
    )
    AND e.EVENT_DT < c.FIRST_DATE
)

--SELECT * FROM fh_cvd
,

--SMOKING STATUS
SMOKING_ALL AS (
    -- Ex smoker
    SELECT e.ALF_PE, e.EVENT_DT, 'EX' AS SMOKER
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD IN (
        '1379.',  -- Ex-moderate smoker
        '137B.',  -- Ex-very heavy smoker
        '137F.',  -- Ex-smoker - amount unknown
        '137j.',  -- Ex-cigarette smoker
        '9km..',  -- Ex-smoker annual review
        '137A.',  -- Ex-heavy smoker
        '137S.',  -- Ex smoker
        '137l.',  -- (variant)
        '137N.',  -- Ex pipe smoker
        '1377',   -- Ex-trivial smoker
        '1378',   -- Ex-light smoker
        '1370.'   -- Stopped smoking
    )
    AND e.EVENT_DT < c.FIRST_DATE

    UNION ALL

    -- Never smoked
    SELECT e.ALF_PE, e.EVENT_DT, 'NEVER' AS SMOKER
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD = '1371.'
    AND e.EVENT_DT < c.FIRST_DATE

    UNION ALL

    -- Heavy smoker
    SELECT e.ALF_PE, e.EVENT_DT, 'HEAVY' AS SMOKER
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD IN ('1375.', '1376.')
    AND e.EVENT_DT < c.FIRST_DATE

    UNION ALL

    -- Moderate smoker
    SELECT e.ALF_PE, e.EVENT_DT, 'MODERATE' AS SMOKER
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD = '1374.'
    AND e.EVENT_DT < c.FIRST_DATE

    UNION ALL

    -- Light smoker
    SELECT e.ALF_PE, e.EVENT_DT, 'LIGHT' AS SMOKER
    FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED e
    INNER JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER c ON e.ALF_PE = c.ALF_PE
    WHERE e.EVENT_CD = '1373.'
    AND e.EVENT_DT < c.FIRST_DATE
),

SMOKING_RANKED AS (
    SELECT
        ALF_PE,
        SMOKER,
        ROW_NUMBER() OVER (
            PARTITION BY ALF_PE
            ORDER BY EVENT_DT DESC
        ) AS RN
    FROM SMOKING_ALL
),

SMOKING AS (
    SELECT ALF_PE, SMOKER
    FROM SMOKING_RANKED
    WHERE RN = 1
)
