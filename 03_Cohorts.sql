,

GP_CKD AS
(
SELECT
ALF_PE,
MAX(CKD) AS CKD
FROM
(
SELECT
GP.ALF_PE,
CASE WHEN EVENT_VAL < 60 THEN 1 ELSE 0 END AS CKD
FROM SAILW1483V.EXTRACT_P2_WLGP_GP_EVENT_CLEANSED GP

JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER G
ON G.ALF_PE = GP.ALF_PE

JOIN SAILUKHDV.READ_CD_CV2_SCD R
ON GP.EVENT_CD = R.READ_CODE

WHERE (R.PREF_TERM_30 LIKE('%eGFR%') OR R.PREF_TERM_30 LIKE('%Glom%'))
		AND EVENT_DT < FIRST_DATE
		AND EVENT_VAL IS NOT NULL
		AND EVENT_VAL > 0	
)
GROUP BY ALF_PE
)

--SELECT * FROM GP_CKD
,


WRRS_CKD AS
(
SELECT
ALF_PE,
MAX(CKD) AS CKD
FROM
(
SELECT
ALF_PE, 
CASE WHEN CAST(VAL AS INTEGER) < 60 THEN 1 ELSE 0 END AS CKD
FROM
(
SELECT
	W.ALF_PE,
	FIRST_DATE AS DIAG,
	SPCM_COLLECTED_DT AS TEST,
	VAL_TYPE,
	CODE,	
	NAME,	
	READ_CD,
	CASE 
		WHEN VAL = '>90' THEN 91
		WHEN VAL = '>60' THEN 61
		ELSE VAL END AS VAL,	
	UNITOFMEASUREMENT
FROM 
	SAILW1483V.EXTRACT_P2_WRRS_OBSERVATION_RESULT W

JOIN SAILW1483V.P2_DIABETES_COHORT_MASTER G
ON W.ALF_PE = G.ALF_PE
	
WHERE NAME LIKE('%GFR%')
	AND SPCM_COLLECTED_DT < FIRST_DATE
	AND VAL IS NOT NULL
	AND VAL_TYPE = 'SN'
	AND VAL NOT IN('AMENDED RESULT','*','{redacted}','NA (Haemolysed specimen)','Serum Haemolysed','Not available.','NA (No sample)','NA','Insufficient sample','<0.1','NA (TEST NOT PERFORMED.)','NA (Insufficient)','>165','<20','Not Tested','<18','<15','Not Available','>3270.8','<13')
)
)
GROUP BY ALF_PE
)

--SELECT * FROM WRRS_EGFR
,

CKD AS
(
SELECT
ALF_PE,
MAX(CKD) AS CKD
FROM
(
SELECT
ALF_PE,
CKD
FROM GP_CKD

UNION

SELECT
ALF_PE,
CKD
